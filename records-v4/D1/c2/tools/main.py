def unit_decision(n, user=False):
    """returns (decision, sentences, what, basis, reason)"""
    tab = uunits if user else units
    d = "/usr/lib/systemd/user/" if user else "/usr/lib/systemd/system/"
    src = RAW + ("0047-user-user-unit-file.out" if user else "0022-unit-file.out")
    st, pre = tab[n]
    p = d + n
    if st in ("enabled", "disabled") and st == pre:
        return SD, "S8.1-11,S8.2-11,S8.2-13,S8.2-17", f"{'user ' if user else ''}unit {n} enablement state: {st}", src, \
            f"Service enablement is a setting (S8.2-13); state '{st}' equals the vendor preset obtained with the package: default value, covered by the package line."
    if st == "enabled":
        return UNK, "S8.2-13,S8.2-17", f"unit {n} enabled although its vendor preset is disabled", src, \
            "Missing fact: what created the enablement link (package scriptlet during installation: SETTING-DEFAULT; image description or person: SETTING-OWN). Not in inventory."
    if st in ("static", "indirect") or (st == "alias" and p in rpm):
        if p in rpm and live_unchanged(p):
            return IP, S_IP, f"packaged unit file {n} ({st}, no enablement of its own)", "raw:package-files.tsv", \
                f"Unit file shipped by {rpm[p][0][0].split('@')[0]}, unchanged; '{st}' has no own enablement value: Q1 yes, covered by the package line."
        return UNK, S_IP, f"unit file {n}", "raw:package-files.tsv", "Missing fact: integrity of the unit file is not recorded."
    if st == "alias":
        tgt = (U_ALIAS_TARGET if user else ALIAS_TARGET)[n]
        td = unit_decision(tgt, user)
        return td[0], td[1], f"alias link {n} created by enabling {tgt}", "raw:raw/0004-filesystem.out", \
            f"Alias link not in any package, created when {tgt} was enabled (link target in snapshot 1); part of that enablement setting: {td[0]}."
    if st in ("masked-runtime", "enabled-runtime"):
        return RT, "S8.2-5", f"unit {n} {st} via a link in /run/systemd/generator", src, \
            "Link under /run/systemd/generator exists only while running; created by a systemd generator (systemd package, installed object): INSTALLED-PACKAGE."
    return None, "", "", "", "UNRULED unit " + st

