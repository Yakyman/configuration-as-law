def level2(o):
    k = o["kind"]; n = o["name"]
    if k == "stored-outside-packages":
        return group(o)
    if k in ("executable-code-outside-packages", "image"):
        return single(n)
    if k == "snapshot" and n == "/etc":
        return MIX, "S8.2-7,S8.2-12,S8.2-15,S8.2-17", "live /etc subvolume holding system configuration (contents not expanded)", "raw:package-files.tsv", \
            "Members differ: packaged files unchanged (e.g. /etc/profile) INSTALLED-PACKAGE; changed person-chosen files (e.g. /etc/default/grub) settings; generated ld.so.cache GAP-TWO; others not expanded."
    if k == "snapshot" and n == "/.snapshots/2/snapshot":
        return MIX, "S8.2-7,S8.2-9,S8.2-15", "live root subvolume (snapshot 2) mounted as /, not expanded", "raw:raw/0004-filesystem.out", \
            "Members differ: packaged files INSTALLED-PACKAGE (package-files.tsv); unowned entries decided by their own rows, e.g. rpm database RECORD, grub copies PROGRAM-DERIVED."
    return None, "", "", "", "UNRULED " + k

