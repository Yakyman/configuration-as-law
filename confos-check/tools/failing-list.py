"""The list of cases that did not pass in a development run, for the builder (TASK.md item 5): for each, the case
ID, the command and the output. Reads runs/NAME/results.tsv and the evidence it names; writes Markdown to stdout.
The comparison of the fresh installation (--base, the compare.tsv of P1-0) is printed once in full; for every other
row only the lines its comparison has beyond the base, and how many lines of the base it lacks. For P4 rows the
effect of the attempt (attempt-effect.tsv) is summarised.

Usage: python3 -I tools/failing-list.py RUNS_DIR/NAME [--stop-at CASE_ID] [--skip ID,...] [--base COMPARE_TSV]
  --stop-at: only the rows before the first row of CASE_ID (a run whose later rows are void)
  --base: the comparison of the fresh installation (default: P1-0/inv-P1-0/compare.tsv of the run)
"""
import collections
import hashlib
import json
import os
import re
import sys

run = sys.argv[1]
_print = print


def print(*a, **k):  # noqa: A001 — every line of the list leaves out the folders of the machine it was made on
    _print(*(re.sub(r'(?:~|/home/[^/\s]+)/VMs/confos/cases/(?:run/[a-z]+/)?', '', str(x)) for x in a), **k)
name = os.path.basename(os.path.normpath(run))


def read(p, limit=None):
    try:
        with open(p, encoding='utf-8', errors='replace') as f:
            t = f.read()
    except OSError:
        return ''
    return t if limit is None else t[-limit:]


def tail_lines(t, n):
    ls = [l for l in t.strip().splitlines() if l.strip()]
    return ls[-n:]


def cmd_text(c):
    x = c.get('command')
    return ' '.join(x) if isinstance(x, list) else str(x)


GEN = re.compile(r'/system/generations/[0-9a-f]{64}/')


def norm(r):
    return tuple(GEN.sub('/system/generations/G/', x) for x in r)


def load_cmp(path):
    return [norm(l.rstrip('\n').split('\t')) for l in read(path).splitlines() if l.strip()]


def summary(rows, limit=40):
    """Verdicts other than UNRECORDED/UNDERIVED in full (at most LIMIT lines); UNDERIVED by reason; UNRECORDED by
    kind, with 2 examples each."""
    out = []
    other = [r for r in rows if r[0] not in ('UNRECORDED', 'UNDERIVED')]
    for r in other[:limit]:
        out.append('    ' + '\t'.join(r)[:400])
    if len(other) > limit:
        out.append(f'    … {len(other) - limit} more lines of verdicts other than UNRECORDED and UNDERIVED')
    under = collections.defaultdict(list)
    for r in rows:
        if r[0] == 'UNDERIVED':
            why = re.sub(r'^.*?reason=', '', r[3] if len(r) > 3 else '')
            why = re.sub(r'^(objects generated by base recipe) \S+', r'\1 V', why)
            under[why[:160]].append(f'{r[1]} {r[2]}')
    if under:
        out.append('    UNDERIVED by reason (what the derivation from the declaration alone cannot give):')
        for why, ids in sorted(under.items(), key=lambda x: -len(x[1])):
            out.append(f'      {len(ids):6d} {why}; e.g. ' + ', '.join(ids[:2])[:200])
    unrec = collections.defaultdict(list)
    for r in rows:
        if r[0] == 'UNRECORDED':
            unrec[r[1]].append(r[2])
    if unrec:
        out.append('    UNRECORDED by kind (objects on the machine that follow from no line):')
        for k, ids in sorted(unrec.items(), key=lambda x: -len(x[1])):
            out.append(f'      {len(ids):6d} {k}, e.g. ' + ', '.join(ids[:2])[:300])
    return out


def compare_block(path):
    """Everything but UNRECORDED in full (at most 40 lines); UNRECORDED as counts by kind with 2 examples each."""
    rows = [l.rstrip('\n').split('\t') for l in read(path).splitlines() if l.strip()]
    if not rows:
        return None
    out = []
    other = [r for r in rows if r[0] not in ('UNRECORDED', 'UNDERIVED')]
    for r in other[:40]:
        out.append('    ' + '\t'.join(r)[:400])
    if len(other) > 40:
        out.append(f'    … {len(other) - 40} more lines of verdicts other than UNRECORDED')
    under = collections.defaultdict(list)
    for r in rows:
        if r[0] == 'UNDERIVED':
            why = re.sub(r'^.*?reason=', '', r[3] if len(r) > 3 else '')
            why = re.sub(r'^(objects generated by base recipe) \S+', r'\1 V', why)
            under[why[:160]].append(f'{r[1]} {r[2]}')
    if under:
        out.append('    UNDERIVED by reason (what the derivation from the declaration alone cannot give):')
        for why, ids in sorted(under.items(), key=lambda x: -len(x[1])):
            out.append(f'      {len(ids):6d} {why}; e.g. ' + ', '.join(ids[:2])[:200])
    unrec = collections.defaultdict(list)
    for r in rows:
        if r[0] == 'UNRECORDED':
            unrec[r[1]].append(r[2])
    if unrec:
        out.append(f'    UNRECORDED by kind (objects on the machine that follow from no line):')
        for k, ids in sorted(unrec.items(), key=lambda x: -len(x[1])):
            out.append(f'      {len(ids):6d} {k}, e.g. ' + ', '.join(ids[:2])[:300])
    return '\n'.join(out)


rows = [l.rstrip('\n').split('\t') for l in read(os.path.join(run, 'results.tsv')).splitlines() if l.strip()]
stop = sys.argv[sys.argv.index('--stop-at') + 1] if '--stop-at' in sys.argv else None
skip = set(sys.argv[sys.argv.index('--skip') + 1].split(',')) if '--skip' in sys.argv else set()
if skip:
    # the evidence directory of a row is that of its case (P1:/UND:/P2-1: rows included)
    rows = [r for r in rows if r[0] not in skip and (len(r) < 4 or r[3].split('/')[0] not in skip)]
if stop:
    cut = next((i for i, r in enumerate(rows) if r[0] == stop or r[0].split(':')[1:2] == [stop]), len(rows))
    rows = rows[:cut]
counts = collections.Counter(r[2] for r in rows)
base_path = sys.argv[sys.argv.index('--base') + 1] if '--base' in sys.argv else '' and \
    os.path.join(run, 'P1-0', 'inv-P1-0', 'compare.tsv')
base = load_cmp(base_path) if os.path.exists(base_path) else []
base_keys = {r[:3] for r in base}
shared = {}      # hash -> (letter, block, [ids])
groups = {}      # (part, outcome, objects) -> rows of P1 and UND that fail on the same objects
entries = []
for r in rows:
    cid, part, outcome, ev = (r + ['', '', '', ''])[:4]
    if outcome == 'pass':
        continue
    case_dir = os.path.join(run, ev.split('/')[0]) if ev else ''
    text = read(os.path.join(run, ev)) if ev else ''
    reasons = [l[len('reason: '):] for l in text.splitlines() if l.startswith('reason: ')]
    m = re.search(r'"compare":\s*"([^"]+)"', text)
    cmp_path = os.path.join(run, os.path.relpath(m.group(1), name)) if m and m.group(1).startswith(name + '/') \
        else (os.path.join(run, m.group(1)) if m else None)
    if cmp_path is None:
        for rs in reasons:
            if rs.startswith('compare') and case_dir:
                inv = [d for d in sorted(os.listdir(case_dir)) if d.startswith('inv-')] if os.path.isdir(case_dir) else []
                if inv:
                    cmp_path = os.path.join(case_dir, inv[-1], 'compare.tsv')
                break
    lines = [f'- **{cid}** ({part}) — `{outcome}`; evidence `runs/{name}/{ev}`']
    for rs in reasons[:12]:
        lines.append(f'  - {rs[:500]}')
    # the command: the step the reason names, else the last command on the machine that exited non-zero
    steps = [re.sub(r'^[A-Z]: ', '', x) for rs in reasons for x in re.findall(r'`([^`]+)`', rs)]
    if steps and case_dir and os.path.exists(os.path.join(case_dir, 'commands.jsonl')):
        recs = []
        for l in read(os.path.join(case_dir, 'commands.jsonl')).splitlines():
            try:
                recs.append(json.loads(l))
            except ValueError:
                pass
        for st in steps[:3]:
            hit = [c for c in recs if st in cmd_text(c) and c.get('exit') not in (0, None)] or \
                  [c for c in recs if st in cmd_text(c)]
            if hit:
                c = hit[-1]
                for x in tail_lines(read(os.path.join(case_dir, c.get('stdout', '')), 4000), 2) + \
                        tail_lines(read(os.path.join(case_dir, c.get('stderr', '')), 4000), 4):
                    lines.append(f'    > {x[:300]}')
    named = any('`' in rs for rs in reasons) or bool(m) or any(
        rs.startswith(('compare', 'derive', 'inventory')) for rs in reasons)
    if not named and case_dir and os.path.exists(os.path.join(case_dir, 'commands.jsonl')):
        last = None
        for l in read(os.path.join(case_dir, 'commands.jsonl')).splitlines():
            try:
                c = json.loads(l)
            except ValueError:
                continue
            if c.get('where') in ('U', 'R') and c.get('exit') not in (0, None):
                if c.get('exit') == 255 and 'closed by remote host' in read(os.path.join(case_dir, c.get('stderr', ''))):
                    continue  # the connection ended by a restart (documented for `confos apply`)
                last = c
        if last:
            err = tail_lines(read(os.path.join(case_dir, last.get('stderr', '')), 4000), 4)
            out = tail_lines(read(os.path.join(case_dir, last.get('stdout', '')), 4000), 2)
            lines.append(f'  - last command on the machine that failed: `{last.get("where")}: {cmd_text(last)[:300]}` '
                         f'exit {last.get("exit")}')
            for x in out + err:
                lines.append(f'    > {x[:300]}')
    eff_path = os.path.join(case_dir, 'attempt-effect.tsv') if case_dir else ''
    if part == 'P4' and ':' not in cid and eff_path and os.path.exists(eff_path):
        eff = [l.split('\t') for l in read(eff_path).splitlines() if l.strip()]
        if eff:
            byk = collections.Counter(f'{e[1]} {e[2]}' for e in eff if len(e) > 2)
            lines.append(f'  - effect of the attempt ({len(eff)} objects; ' +
                         ', '.join(f'{n} {k}' for k, n in byk.most_common(6)) + '):')
            for e in eff[:8]:
                lines.append('    ' + '\t'.join(e[1:])[:300])
    own = None
    if part in ('P1', 'UND', 'P2') and case_dir:
        # since [n2-1]: every P1 row is compared against the reference installation (compare-p1.tsv), the easier reading
        # of UND against it too (compare-und-reference.tsv), P2 against the derivation (compare.tsv); each is short
        # and is printed in full
        if part == 'UND':
            mu = re.search(r'"compare":\s*"([^"]*compare-und-reference\.tsv)"', text)
            own = os.path.join(run, os.path.relpath(mu.group(1), name)) if mu and mu.group(1).startswith(name + '/') \
                else (os.path.join(run, mu.group(1)) if mu else None)
            want = None
        elif part == 'P1':
            own, want = cmp_path, None
        else:
            own, want = cmp_path, ('MISSING', 'DIFFERS', 'UNVERIFIED')
    if own and os.path.exists(own):
        sel = [r for r in load_cmp(own) if (want is None and r[0] != 'UNDERIVED') or (want and r[0] in want)]
        # rows of P1 and UND that differ in nothing but the row ID are printed once, as a group (below)
        gkey = (part, outcome, tuple(sorted(tuple(r[:3]) for r in sel)))
        if part in ('P1', 'UND') and ':' in cid:
            g = groups.setdefault(gkey, {'ids': [], 'sample': None})
            g['ids'].append(cid)
            if g['sample'] is None:
                g['sample'] = (reasons, own, sel)
            continue

        lines.append(f'  - `{os.path.relpath(own, os.path.dirname(run))}`: {len(sel)} line(s)' +
                     (' other than UNDERIVED' if want is None else ' MISSING/DIFFERS/UNVERIFIED') +
                     (':' if sel else ''))
        lines.extend('    ' + '\t'.join(r)[:400] for r in sel[:30])
        if len(sel) > 30:
            lines.append(f'    … {len(sel) - 30} more')
    elif cmp_path and os.path.exists(cmp_path) and base:

        cur = load_cmp(cmp_path)
        keys = {r[:3] for r in cur}
        extra = [r for r in cur if r[:3] not in base_keys]
        lack = len(base_keys - keys)
        lines.append(f'  - comparison `{os.path.relpath(cmp_path, os.path.dirname(run))}`: the base comparison '
                     f'(below){f", minus {lack} of its lines" if lack else ""}'
                     + (f', plus these {len(extra)} lines:' if extra else ', nothing more'))
        if extra and ':' in cid:
            # P1:/UND:/P2-1: rows of a case: the objects the case added are in the row of the case itself; here
            # the counts, and the lines other than UNRECORDED in full
            c = collections.Counter(r[0] for r in extra)
            lines[-1] = lines[-1][:-1] + ' (' + ', '.join(f'{n} {v}' for v, n in c.most_common()) + ')' + \
                (':' if any(r[0] != 'UNRECORDED' for r in extra) else '')
            lines.extend('    ' + '\t'.join(r)[:300] for r in [r for r in extra if r[0] != 'UNRECORDED'][:10])
        elif extra:
            lines.extend('  ' + x for x in summary(extra, limit=15))
    elif cmp_path and os.path.exists(cmp_path):
        blk = compare_block(cmp_path)
        if blk:
            h = hashlib.sha256(re.sub(r'/system/generations/[0-9a-f]{64}/', '/system/generations/G/', blk)
                               .encode()).hexdigest()
            if h not in shared:
                shared[h] = (chr(ord('A') + len(shared)) if len(shared) < 26 else f'Z{len(shared)}', blk, [])
            shared[h][2].append(cid)
            lines.append(f'  - comparison `{os.path.relpath(cmp_path, os.path.dirname(run))}`: set {shared[h][0]} below')
    entries.append('\n'.join(lines))

print(f'Development run `{name}` (not an observation of the check)'
      + (f', rows before `{stop}` only (the later rows are void)' if stop else '')
      + (f', without the rows of {", ".join(sorted(skip))} (rerun in another part)' if skip else '')
      + f': {len(rows)} rows, '
      + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())) + '. Every row that did not pass:\n')
print('\n'.join(entries))
if base:
    print(f'\nBase comparison: the fresh installation (`{os.path.relpath(base_path, os.path.dirname(run))}`; '
          'G = the generation in force):\n')
    print('\n'.join(summary(base)))
if shared:
    print('\nComparison sets (the lines of `compare.tsv`; G = the generation in force):\n')
    for letter, blk, ids in shared.values():
        print(f'- Set {letter} ({len(ids)} rows):\n')
        print(re.sub(r'/system/generations/[0-9a-f]{64}/', '/system/generations/G/', blk))
        print()
if groups:
    print('\nRows of P1 and UND grouped by the objects they count (each group: the rows, one sample of the reasons, and '
          'the lines of the comparison, which are the same in every row of the group):\n')
    for (part, outcome, objs), g in sorted(groups.items(), key=lambda x: (-len(x[1]['ids']), x[0][0])):
        reasons, own, sel = g['sample']
        print(f'- **{len(g["ids"])} {part} rows `{outcome}`**: ' + ', '.join(g['ids']))
        for rs in reasons[:4]:
            print(f'  - (first row) {rs[:400]}')
        print(f'  - lines of `{os.path.relpath(own, os.path.dirname(run))}` (first row):')
        for r in sel[:30]:
            print('    ' + '\t'.join(r)[:400])
        if len(sel) > 30:
            print(f'    … {len(sel) - 30} more')
